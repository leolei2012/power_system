"""Small, backed-up PCB review fixes; preserves all component/pad connectivity.

Run with KiCad's bundled Python. Adds pour-only mounting margins, mirrors
source BOM/datasheet metadata and uses KiCad's internal escape for slash in
autogenerated BAT54S pin-name nets. No schematic or shared library is edited.
"""
from pathlib import Path
import hashlib,json,math,shutil
import xml.etree.ElementTree as ET
import pcbnew as p

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'outputs/pcb_review_2026-11-11/finalization'
OUT.mkdir(parents=True,exist_ok=True)
MM=p.FromMM


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    results={}
    for role,folder,board_path in [
        ('controller',ROOT/'controller/hardware/g431_core',ROOT/'controller/hardware/g431_core/controller.kicad_pcb'),
        ('inverter',ROOT/'inverter/hardware',ROOT/'inverter/hardware/review/pcb_rev_e_2026-11-11/power/inverter.kicad_pcb')]:
        before=sha(board_path)
        backup=OUT/(role+'_before_metadata_and_pour_margin.kicad_pcb')
        if not backup.exists():shutil.copyfile(board_path,backup)
        board=p.LoadBoard(str(board_path))
        fps={f.GetReference():f for f in board.GetFootprints()}
        xml=ET.parse(folder/'review'/(role+'.net.xml')).getroot()
        flags=[];fields=[];escaped=[];guards=[]
        for part in xml.findall('./components/comp'):
            fp=fps[part.get('ref')]
            excluded=part.find("property[@name='exclude_from_bom']") is not None
            attrs=fp.GetAttributes()
            desired=(attrs|p.FP_EXCLUDE_FROM_BOM) if excluded else (attrs&~p.FP_EXCLUDE_FROM_BOM)
            if desired!=attrs:fp.SetAttributes(desired);flags.append(fp.GetReference())
            source={field.get('name'):field.text or '' for field in part.findall('./fields/field')}
            for key in ['Datasheet_File']:
                if fp.HasField(key) and key in source and fp.GetFieldText(key)!=source[key]:
                    fp.SetField(key,source[key]);fields.append(fp.GetReference()+'.'+key)
        for net in board.GetNetsByNetcode().values():
            name=net.GetNetname()
            if name.startswith('Net-(D20') and 'K1/A2' in name:
                new=name.replace('K1/A2','K1{slash}A2');net.SetNetname(new);escaped.append([name,new])
        zone_names={z.GetZoneName() for z in board.Zones()}
        for ref in ['H1','H2','H3','H4']:
            name='REV E / '+ref+' pour-only 3.0 mm margin'
            if name in zone_names:continue
            centre=fps[ref].GetPosition()
            z=p.ZONE(board);layers=p.LSET()
            for layer in board.GetEnabledLayers().CuStack():layers.AddLayer(layer)
            z.SetLayerSet(layers);z.SetIsRuleArea(True);z.SetZoneName(name)
            z.SetDoNotAllowZoneFills(True);z.SetDoNotAllowTracks(False);z.SetDoNotAllowVias(False)
            z.SetDoNotAllowPads(False);z.SetDoNotAllowFootprints(False)
            outline=z.Outline();outline.NewOutline()
            radius=3.0/math.cos(math.pi/64)
            for i in range(64):
                a=2*math.pi*i/64
                outline.Append(centre.x+MM(radius*math.cos(a)),centre.y+MM(radius*math.sin(a)))
            board.Add(z);guards.append(name)
        board.BuildConnectivity();p.ZONE_FILLER(board).Fill(board.Zones())
        p.SaveBoard(str(board_path),board)
        actual=p.LoadBoard(str(board_path))
        pin_nets={(n.get('ref'),n.get('pin')):net.get('name') for net in xml.findall('./nets/net') for n in net.findall('node')}
        for f in actual.GetFootprints():
            if f.GetReference().startswith('H'):continue
            for pad in f.Pads():
                if pad.GetNumber():assert pad.GetNetname().replace('{slash}','/')==pin_nets[(f.GetReference(),pad.GetNumber())]
        results[role]={'before_sha256':before,'after_sha256':sha(board_path),'board':str(board_path),
                       'BOM_flags_mirrored_from_schematic':flags,'datasheet_fields_mirrored':fields,
                       'same_net_name_escape_changes':escaped,'pour_only_margin_added':guards,
                       'minimum_mounting_copper_radius_mm':2.8,'pour_margin_radius_mm':3.0,
                       'pad_net_mapping_after_save_reload':'PASS'}
    (OUT/'report.json').write_text(json.dumps(results,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({name:{'mapping':'PASS','BOM_flag_updates':len(r['BOM_flags_mirrored_from_schematic']),
                            'escaped_net_names':len(r['same_net_name_escape_changes']),
                            'pour_guards':len(r['pour_only_margin_added'])} for name,r in results.items()}))


if __name__=='__main__':main()
